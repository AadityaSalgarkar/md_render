/**
 * Theme registry — the single source of truth for every visual theme.
 *
 * A theme is just a bag of CSS custom properties. `useTheme` applies one by
 * setting `<html data-theme="...">` and writing each var via `style.setProperty`.
 * `src/index.css` keeps the Warm Paper values on `:root` as the default so the
 * very first paint is never unstyled.
 */

export type ThemeMode = 'light' | 'dark'

/** Every CSS custom property a theme must define. */
export const THEME_VARS = [
  // Surfaces
  '--bg-primary',
  '--bg-secondary',
  '--bg-editor',
  '--bg-preview',
  // Text
  '--text-primary',
  '--text-secondary',
  '--text-muted',
  // Accents
  '--accent',
  '--accent-hover',
  '--accent-secondary',
  // Lines & code surface
  '--border',
  '--border-strong',
  '--code-bg',
  '--selection',
  '--shadow-fold',
  // Display math: the book themes set it in a tinted panel; the bare
  // web-page themes leave it on the page, as MathJax does.
  '--math-display-bg',
  '--math-display-padding',
  // Typography
  '--font-head',
  '--font-body',
  '--font-mono',
  // Syntax highlighting
  '--code-keyword',
  '--code-string',
  '--code-number',
  '--code-comment',
  '--code-function',
  '--code-builtin',
  // Plot series hues, in the order groups take them
  '--chart-1',
  '--chart-2',
  '--chart-3',
  '--chart-4',
  '--chart-5',
  '--chart-6',
  '--chart-7',
  '--chart-8',
] as const

export type ThemeVar = (typeof THEME_VARS)[number]

export interface ThemeDefinition {
  id: string
  name: string
  mode: ThemeMode
  /** One-line personality summary shown in the picker. */
  blurb: string
  vars: Record<ThemeVar, string>
}

/** The theme's main colours, as the picker shows them: page, text, accent. */
export function themeSwatch(theme: ThemeDefinition): [string, string, string] {
  return [theme.vars['--bg-primary'], theme.vars['--text-primary'], theme.vars['--accent']]
}

